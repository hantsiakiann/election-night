"""Build config/candidates.yml from raw "RACE|Name|Party" lists.

    python tools/build_candidates.py senate.txt governor.txt house*.txt

Raw lines: "GA|Jon Ossoff|D" for Senate/Governor files (file name says which), or
"GA-05|Name|D" / "AK-AL|Name|R" for House. Rules applied:
- In states without top-two/top-four primaries, a party listed more than once in a district
  came from a pre-primary filing list, so that party's entries are dropped (we don't guess
  the nominee). California, Washington and Alaska keep same-party candidates.
- Party names are normalized to D, R, L, G, I, C where possible; other parties keep their name.
These are preliminary lists; live feeds replace them, and config/manual.yml can override.
"""
import sys
from collections import OrderedDict, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MULTI_OK = {"CA", "WA", "AK"}
PARTY = {
    "d": "D", "dem": "D", "democrat": "D", "democratic": "D", "dfl": "D", "democratic–npl": "D",
    "democratic-npl": "D", "r": "R", "rep": "R", "republican": "R",
    "l": "L", "lib": "L", "libertarian": "L", "g": "G", "green": "G", "pacific green": "G",
    "i": "I", "ind": "I", "independent": "I", "unaffiliated": "I", "no labels": "No Labels",
    "c": "C", "constitution": "C", "constitution party": "C", "u.s. taxpayers": "C",
}


def norm_party(p):
    p = (p or "").strip()
    return PARTY.get(p.lower(), p)


def main(files):
    races = defaultdict(list)
    for f in files:
        kind = "senate" if "senate" in f else "governor" if "governor" in f else "house"
        for line in Path(f).read_text().splitlines():
            parts = [x.strip() for x in line.split("|")]
            if len(parts) < 2 or not parts[1] or parts[0] == "LAST":
                continue
            key, name, party = parts[0], parts[1], norm_party(parts[2] if len(parts) > 2 else "")
            if kind == "house":
                st, d = key.split("-")
                rid = f"H-{st}-{d}"
            else:
                st, rid = key, ("SEN-" if kind == "senate" else "GOV-") + key
            if any(c["name"] == name for c in races[rid]):
                continue
            races[rid].append({"name": name, "party": party, "_st": st})
    out, dropped = OrderedDict(), []
    for rid in sorted(races):
        cands = races[rid]
        st = cands[0]["_st"]
        count = defaultdict(int)
        for c in cands:
            count[c["party"]] += 1
        keep = []
        for c in cands:
            if st not in MULTI_OK and c["party"] in ("D", "R") and count[c["party"]] > 1:
                dropped.append(f"{rid} {c['name']} ({c['party']})")
                continue
            keep.append({"name": c["name"], "party": c["party"]} if c["party"] else {"name": c["name"]})
        if keep:
            out[rid] = keep
    header = ("# Preliminary candidate lists shown before results arrive (generated by\n"
              "# tools/build_candidates.py from Wikipedia, The Green Papers and 270toWin, Oct 2026).\n"
              "# Races with a live feed use the feed's candidates instead. Edit freely.\n")
    path = ROOT / "config/candidates.yml"
    path.write_text(header + yaml.safe_dump({"races": dict(out)}, sort_keys=False, allow_unicode=True, width=200))
    n_house = sum(1 for k in out if k.startswith("H-"))
    print(f"wrote {path}: {len(out)} races ({sum(1 for k in out if k.startswith('SEN-'))} Senate, "
          f"{sum(1 for k in out if k.startswith('GOV-'))} governor, {n_house} House); "
          f"dropped {len(dropped)} ambiguous pre-primary entries")


if __name__ == "__main__":
    main(sys.argv[1:])
